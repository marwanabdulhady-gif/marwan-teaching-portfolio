#!/usr/bin/env python3
"""Build the static course index used by the /courses learning map.

Reads the lesson app that ships in `public/academy/**` (read-only) and writes
generated, committed artefacts:

  public/courses/questions.json      the 162-question bank, served lazily
  src/courses/data/questionIndex.json  { lessonKey: [questionId, ...] }
  src/courses/data/lessonTopics.json   { lessonKey: [topic, ...] }
  src/courses/gmatTopics.ts            38 GMAT topics with real titles

Question -> lesson mapping is *measured*, not guessed: every question in the
bank carries `data-guided-question="<id>"` on exactly one lesson page, so we
scan the lesson HTML instead of inferring id prefixes. Any question that
cannot be found is reported (never silently guessed).

Run from the repo root:  python3 scripts/build-course-index.py
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COURSES = ROOT / "public" / "academy" / "courses"
SOURCE = ROOT / "drmathazzam-clone" / "source"
DATA_OUT = ROOT / "src" / "courses" / "data"
PUBLIC_OUT = ROOT / "public" / "courses"

GUIDED_ATTR = re.compile(r'data-guided-question="([^"]+)"')
H1 = re.compile(r"<h1[^>]*>(.*?)</h1>", re.DOTALL)
TAG = re.compile(r"<[^>]+>")


def lesson_pages() -> dict[str, Path]:
    """Map `courseSlug/lessonId` -> index.html for every lesson page."""
    pages: dict[str, Path] = {}
    for path in sorted(COURSES.glob("*/lessons/*/index.html")):
        lesson_id = path.parent.name
        course_slug = path.parent.parent.parent.name
        pages[f"{course_slug}/{lesson_id}"] = path
    return pages


def build_question_index(pages: dict[str, Path], bank: dict) -> dict[str, list[str]]:
    index: dict[str, list[str]] = {key: [] for key in pages}
    seen: dict[str, str] = {}
    for key, path in pages.items():
        html = path.read_text(encoding="utf-8", errors="ignore")
        for qid in GUIDED_ATTR.findall(html):
            if qid in seen and seen[qid] != key:
                print(f"  ! {qid} appears in both {seen[qid]} and {key}", file=sys.stderr)
            seen[qid] = key
            if qid in bank and qid not in index[key]:
                index[key].append(qid)

    unassigned = [qid for qid in bank if qid not in seen]
    unknown = [qid for qid in seen if qid not in bank]
    if unassigned:
        print(f"  ! {len(unassigned)} question(s) not linked to any lesson page:" + " " + ", ".join(unassigned))
    if unknown:
        print(f"  ! {len(unknown)} attribute id(s) missing from the bank:" + " " + ", ".join(unknown))
    print(f"  mapped {len(bank) - len(unassigned)}/{len(bank)} questions across "
          f"{sum(1 for v in index.values() if v)} lessons")
    return index


def build_topics(pages: dict[str, Path]) -> dict[str, list[str]]:
    lessons = json.loads((SOURCE / "lessons.json").read_text(encoding="utf-8"))
    topics = {
        f"{lesson['courseSlug']}/{lesson['id']}": lesson.get("topics", [])
        for lesson in lessons
    }
    missing = [key for key in pages if not topics.get(key)]
    if missing:
        print(f"  ! no topics for: {', '.join(missing)}")
    return topics


def build_gmat_topics() -> list[dict[str, str]]:
    topics: list[dict[str, str]] = []
    for group in ("quant", "di"):
        for path in sorted((COURSES / "gmat-preparation" / group).glob("*/index.html")):
            slug = path.parent.name
            html = path.read_text(encoding="utf-8", errors="ignore")
            match = H1.search(html)
            title = TAG.sub("", match.group(1)).strip() if match else slug.replace("-", " ").title()
            title = re.sub(r"\s+", " ", title)
            topics.append(
                {
                    "slug": slug,
                    "group": group,
                    "title": title,
                    "href": f"/academy/courses/gmat-preparation/{group}/{slug}/index.html",
                }
            )
    return topics


def write_json(path: Path, payload) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"  wrote {path.relative_to(ROOT)}")


def write_gmat_ts(path: Path, topics: list[dict[str, str]]) -> None:
    quant = sum(1 for t in topics if t["group"] == "quant")
    lines = [
        "/**",
        " * GMAT topics, generated by `scripts/build-course-index.py`.",
        " * Titles come from the <h1> of each topic page; do not edit by hand.",
        " */",
        "",
        "export interface GmatTopic {",
        "  slug: string;",
        "  group: 'quant' | 'di';",
        "  title: string;",
        "  href: string;",
        "}",
        "",
        "export const GMAT_TOPICS: GmatTopic[] = [",
    ]
    for topic in topics:
        lines.append(
            "  { slug: %s, group: '%s', title: %s, href: %s },"
            % (
                json.dumps(topic["slug"]),
                topic["group"],
                json.dumps(topic["title"], ensure_ascii=False),
                json.dumps(topic["href"]),
            )
        )
    lines += [
        "];",
        "",
        f"export const GMAT_COUNT = {{ quant: {quant}, di: {len(topics) - quant}, total: {len(topics)} }};",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"  wrote {path.relative_to(ROOT)} ({len(topics)} topics)")


def main() -> int:
    if not COURSES.is_dir():
        print(f"missing {COURSES}", file=sys.stderr)
        return 1
    print("Building course index…")
    pages = lesson_pages()
    print(f"  found {len(pages)} lesson pages")

    raw = json.loads((SOURCE / "question-bank.json").read_text(encoding="utf-8"))
    # The bank is an id-keyed object, but accept a list too in case it changes.
    bank_list = list(raw.values()) if isinstance(raw, dict) else raw
    bank = {item["id"]: item for item in bank_list}

    question_index = build_question_index(pages, bank)
    topics = build_topics(pages)

    write_json(PUBLIC_OUT / "questions.json", bank_list)
    write_json(DATA_OUT / "questionIndex.json", question_index)
    write_json(DATA_OUT / "lessonTopics.json", topics)
    write_gmat_ts(ROOT / "src" / "courses" / "gmatTopics.ts", build_gmat_topics())
    print("Done.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
